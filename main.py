# ── Paths ─────────────────────────────────────────────────────────────────────

BASE_DIR             = os.path.dirname(os.path.abspath(__file__))
CLIENTS_FILE         = os.path.join(BASE_DIR, "clients.json")
ROTATION_FILE        = os.path.join(BASE_DIR, "device_rotation.json")
